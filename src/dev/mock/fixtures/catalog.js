export function xpForLevel(level) {
  const l = Math.max(1, Math.min(XP_FOR_LEVEL.length, level));
  return XP_FOR_LEVEL[l - 1];
}

export function levelForXp(xp) {
  let level = 1;
  for (let i = 0; i < XP_FOR_LEVEL.length; i += 1) if (xp >= XP_FOR_LEVEL[i]) level = i + 1;
  return level;
}

